#!/usr/bin/env bash
# Regenerate engine.mjs from a RealPFP checkout so the skill stays in step with
# the app's prompt logic. Needs bun (used only as a TypeScript stripper).
#   bash sync-engine.sh <path to RealPFP checkout>
# Inside the RealPFP repo (skills/realpfp/scripts) the path can be left out.
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
repo="${1:-$here/../../..}"
src="$repo/app/page.tsx"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

[ -f "$src" ] || { echo "No $src" >&2; exit 1; }
command -v bun >/dev/null || { echo "bun is required to strip TypeScript" >&2; exit 1; }

start=$(grep -n '^const RANDOM_TRAITS = {' "$src" | cut -d: -f1)
end=$(grep -n '^function useIsMobile' "$src" | cut -d: -f1)
[ -n "$start" ] && [ -n "$end" ] || { echo "Markers not found in page.tsx; the engine moved" >&2; exit 1; }

sed -n "${start},$((end - 1))p" "$src" > "$tmp/engine.ts"
bun build --no-bundle --target=node "$tmp/engine.ts" > "$tmp/engine.js"

commit=$(git -C "$repo" rev-parse --short HEAD 2>/dev/null || echo unknown)
{
  echo "// GENERATED by sync-engine.sh from RealPFP app/page.tsx @ $commit. Do not edit by hand."
  echo "// Source: https://github.com/heyimjames/RealPFP"
  cat "$tmp/engine.js"
  echo
  echo "export { generateRandomPrompt, AI_PARAM_DEFS, RANDOM_TRAITS, ATMOSPHERES, FREQUENCY_DEFAULTS, ETHNICITY_DEFAULT_WEIGHTS, DEFAULT_ETHNICITY_WEIGHTS_STATE };"
} > "$here/engine.mjs"

node --check "$here/engine.mjs"
echo "engine.mjs synced from $commit"
